"""Fit a beat grid to the detected onsets and emit it as a TypeScript constant."""

from __future__ import annotations

import json
import sys
from pathlib import Path

FPS = 30.0


def main() -> None:
    beats_path = Path(sys.argv[1])
    out_path = Path(sys.argv[2])
    data = json.loads(beats_path.read_text(encoding="utf-8"))
    duration = float(data["duration"])
    bpm = float(data["bpm"])
    onsets = sorted(float(t) for t in data["beats"])

    period = 60.0 / bpm

    # The autocorrelation peak can land on a multiple of the real pulse. Search
    # candidate periods and keep the one that actually explains the onsets.
    def coverage_for(p: float, ph: float) -> float:
        hit = 0
        for t in onsets:
            k = round((t - ph) / p)
            error = abs(t - (ph + k * p))
            if error < 0.05:
                hit += 1 - error / 0.05
        return hit

    best_period, best_period_phase, best_period_score = period, 0.0, -1.0
    for ratio in (0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 4.0):
        p = period / ratio
        if p < 0.18 or p > 1.4:
            continue
        for i in range(200):
            ph = p * i / 200
            score = coverage_for(p, ph)
            if score > best_period_score:
                best_period, best_period_phase, best_period_score = p, ph, score

    print(f"pulse search : best {best_period:.4f}s ({60.0 / best_period:.2f} BPM)"
          f" phase {best_period_phase:.4f}s  matched {best_period_score:.0f}/{len(onsets)}")

    # The surface pulses at the searched rate; the film's accent grid is two of
    # those, which is the tempo the listener counts. Pick the better of the two
    # sub-phases so section changes land on the stronger of them.
    accent_period = best_period * 2
    phase_a = best_period_phase
    phase_b = (best_period_phase + best_period) % accent_period
    if coverage_for(accent_period, phase_b) > coverage_for(accent_period, phase_a):
        phase_a = phase_b
    score = coverage_for(accent_period, phase_a)
    print(f"accent grid  : {accent_period:.4f}s ({60.0 / accent_period:.2f} BPM)"
          f" phase {phase_a:.4f}s  matched {score:.0f}/{len(onsets)}")
    period = accent_period
    forced_phase = phase_a

    # Search the phase that puts the most onsets close to a grid line.
    best_phase, best_score = forced_phase, -1
    steps = 400
    for i in range(steps):
        phase = period * i / steps
        score = 0
        for t in onsets:
            k = round((t - phase) / period)
            error = abs(t - (phase + k * period))
            if error < 0.06:
                score += 1 - error / 0.06
        if score > best_score:
            best_phase, best_score = phase, score

    count = int((duration - best_phase) // period) + 1
    grid = [best_phase + k * period for k in range(count)]
    grid = [t for t in grid if t <= duration]
    frames = sorted({int(round(t * FPS)) for t in grid})

    coverage = sum(
        1 for t in onsets
        if any(abs(t - g) < 0.06 for g in grid)
    )
    print(f"bpm          : {bpm:.3f}  period {period:.4f}s")
    print(f"phase        : {best_phase:.4f}s  (score {best_score:.1f})")
    print(f"grid points  : {len(grid)}  (frames {frames[0]}..{frames[-1]})")
    print(f"onset match  : {coverage}/{len(onsets)} detected onsets within 60ms of a grid line")
    print(f"bar length   : {period * 4:.3f}s  ({round(period * 4 * FPS)} frames)")

    lines = [
        "// Generated by tools/beat_grid.py from assets/bgm_beats.json. Do not edit by hand.",
        f"// Tempo {bpm:.3f} BPM, period {period:.4f}s, phase {best_phase:.4f}s, {FPS:g} fps.",
        "",
        f"export const BPM = {bpm:.4f};",
        f"export const BEAT_SECONDS = {period:.6f};",
        f"export const BAR_FRAMES = {round(period * 4 * FPS)};",
        f"export const DURATION_SECONDS = {duration:.6f};",
        "",
        "export const ACCENT_FRAMES: readonly number[] = [",
    ]
    for i in range(0, len(frames), 16):
        lines.append("  " + ", ".join(str(f) for f in frames[i:i + 16]) + ",")
    lines.append("];")
    lines.append("")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"written      : {out_path}")


if __name__ == "__main__":
    main()
